package target

import "testing"

func TestChangedFuncsResolvesOverlapNotContainment(t *testing.T) {
	// A hunk that starts above a function and runs into it must still select
	// that function: the signature or a doc comment changing can change
	// behaviour just as much as the body.
	src := []byte(`package p

// Sum adds.
func Sum(xs []int) int {
	t := 0
	for _, x := range xs {
		t += x
	}
	return t
}

func Untouched() {}
`)
	got, err := ChangedFuncs("calc.go", src, []LineRange{{Start: 3, End: 5}})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 {
		t.Fatalf("got %d funcs, want 1: %+v", len(got), got)
	}
	if got[0].Name != "Sum" {
		t.Errorf("name = %q, want Sum", got[0].Name)
	}
}

func TestChangedFuncsSkipsGeneratedFiles(t *testing.T) {
	// Mutating or grading generated code measures the generator, not the author.
	src := []byte(`// Code generated by protoc-gen-go. DO NOT EDIT.

package p

func Generated() { println("x") }
`)
	got, err := ChangedFuncs("x.pb.go", src, []LineRange{{Start: 1, End: 6}})
	if err != nil {
		t.Fatal(err)
	}
	if got != nil {
		t.Errorf("got %+v, want nothing from a generated file", got)
	}
}

func TestFuncKeyDistinguishesMethodsOfTheSameName(t *testing.T) {
	src := []byte(`package p

type A struct{}
type B struct{}

func (a *A) Do() {}
func (b B) Do()  {}
func Do()        {}
`)
	got, err := ChangedFuncs("x.go", src, []LineRange{{Start: 1, End: 9}})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 3 {
		t.Fatalf("got %d funcs, want 3", len(got))
	}
	seen := map[string]bool{}
	for _, f := range got {
		if seen[f.Key()] {
			t.Errorf("duplicate key %q — methods would be diffed against the wrong base", f.Key())
		}
		seen[f.Key()] = true
	}
	// The pointer star is not part of the identity: *A and A are one type.
	if got[0].Recv != "A" {
		t.Errorf("recv = %q, want A (no star)", got[0].Recv)
	}
}
